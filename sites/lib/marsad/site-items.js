export const siteKey = t => String(t || '').replace(/[ً-ْـ]/g, '').replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
  .replace(/[^؀-ۿ0-9]+/g, '');
const WEIGHED = new Set(Object.values(SITE_ITEMS).filter(v => Array.isArray(v) && v.length === 4 && /^010[78]/.test(v[0])).map(v => v.join()));
const INDEX = new Map(Object.entries(SITE_ITEMS).map(([name, v]) => [siteKey(name), Array.isArray(v) ? { nos: v, by: [], weighed: WEIGHED.has(v.join()) } : v]));

// The Apex candidates for a website dish, narrowed by the chosen weight (`size` = [, regex on Apex names]) and the
// order's own words (`text`). Returns { nos, pick } — pick only when exactly one item is left.
export function siteApexItems(name, { size = null, text = '', apexName = null } = {}) {
  const e = INDEX.get(siteKey(name));
  if (!e) return null;
  let nos = e.nos.slice();
  if (size && nos.length > 1 && apexName) { const s = nos.filter(no => size[1].test(apexName.get(no) || '')); if (s.length) nos = s; }
  if (nos.length > 1 && e.by.length) {
    const t = String(text || '').replace(/[أإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه');
    const hit = e.by.find(([re]) => re.test(t));
    if (hit && nos.includes(hit[1])) nos = [hit[1]];
  }
  return { nos, pick: nos.length === 1 ? nos[0] : null, weighed: !!e.weighed };
}
