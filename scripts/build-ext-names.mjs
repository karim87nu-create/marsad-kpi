// Writes extension-3/names.js from the server's name lists (sites/lib/marsad/arabic-names.js), so the extension turns
// Talabat customers' English names into Arabic before the order reaches the server (Karim 11-18: no publish needed).
import { writeFileSync } from 'node:fs';
import { NAMES, skeleton } from '../sites/lib/marsad/arabic-names.js';
const names = {}, skel = {};
const votes = new Map();
for (const [k, v] of Object.entries(NAMES)) {
  if (k.length < 2 || k.includes(' ') || (v.startsWith('ال') && !/^(el|al)/.test(k))) continue;   // people's names only
  names[k] = v;
  const sk = k.length >= 3 ? skeleton(k) : ''; if (!sk) continue;
  const m = votes.get(sk) || new Map(); m.set(v, (m.get(v) || 0) + 1); votes.set(sk, m);
}
for (const [sk, m] of votes) { const [[a, n], second] = [...m].sort((x, y) => y[1] - x[1]); if (!second || n >= 3 * second[1]) skel[sk] = a; }
const src = `// Generated by scripts/build-ext-names.mjs from the server's name lists — do not edit by hand.
// A Talabat customer's English name → Arabic before the order is sent (Karim 11-18 «أسماء العملاء بتتكتب غلط جدا»):
// a known spelling, or one with the same consonants as a known name; a word not known stays as it is.
(() => {
  const NAMES = ${JSON.stringify(names)};
  const SKEL = ${JSON.stringify(skel)};
  ${skeleton.toString()}
  const PLACEHOLDER = /^(?:unknown|n\\/?a|none|null|guest|customer|talabat( customer)?|-+|\\.+|x+)$/i;
  globalThis.MARSAD_NAME = name => {
    const raw = String(name || '').replace(/\\s+/g, ' ').trim();
    if (!raw || PLACEHOLDER.test(raw)) return '';
    return raw.split(' ').map(w => {
      const k = w.toLowerCase().replace(/['’\`]/g, '');
      if (!/^[a-z0-9'’\`\\-]+$/i.test(w) || /^(el|al)$/.test(k)) return w;   // «El Gazzar»: the server joins «El» to the next word
      const el = k.match(/^(el|al)-?(.{3,})$/);
      const one = x => NAMES[x] || (x.length >= 3 ? SKEL[skeleton(x)] : null);
      return one(k) || (el && one(el[2]) ? 'ال' + one(el[2]).replace(/^ال/, '') : null) || w;
    }).join(' ');
  };
  // The customer's name in Arabic before it leaves the page, the English kept beside it.
  globalThis.MARSAD_NAME_PAIR = n => { const en = String(n || '').trim(), ar = globalThis.MARSAD_NAME(en); return ar === en ? { name: en } : { name: ar, nameEn: en }; };
})();
`;
writeFileSync(new URL('../extension-3/names.js', import.meta.url), src);
console.log('names', Object.keys(names).length, 'skeletons', Object.keys(skel).length, 'bytes', src.length);
